/// Metadata for a single supported language.
class AppLanguage {
  /// Storage key matching the existing Settings selection (e.g. 'Urdu').
  final String name;

  /// Name written in the language's own script.
  final String nativeName;

  /// BCP-47 locale used for speech-to-text, or null if not reliably supported.
  final String? sttLocale;

  /// BCP-47 locale used for text-to-speech, or null if not reliably supported.
  final String? ttsLocale;

  /// Whether the language is right-to-left.
  final bool isRtl;

  const AppLanguage({
    required this.name,
    required this.nativeName,
    this.sttLocale,
    this.ttsLocale,
    this.isRtl = false,
  });

  bool get supportsStt => sttLocale != null;
  bool get supportsTts => ttsLocale != null;
}

