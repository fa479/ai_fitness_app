/// Lightweight string-translation helper. Looks up a key for the active
/// language, falling back to English then to the raw key.
class L {
  L._();

  static String _current = 'English';

  static String get current => _current;

  static AppLanguage get language => AppLanguages.byCode(_current);

  static bool get isRtl => language.isRtl;

  static Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    _current = prefs.getString('language') ?? 'English';
  }

  static Future<void> set(String name) async {
    _current = name;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('language', name);
  }

  /// Translate a UI string key.
  static String t(String key) {
    final translations = _strings[key];
    if (translations == null) return key;
    return translations[_current] ?? translations['English'] ?? key;
  }

  /// Directionality-aware builder for the whole app.
  static TextDirection get textDirection =>
      isRtl ? TextDirection.rtl : TextDirection.ltr;
}

